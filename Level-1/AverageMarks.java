public class AverageMarks {
    public static void main(String[] args) {
        int marks1 = 85;
        int marks2 = 90;
        int marks3 = 78;
        int totalMarks = marks1 + marks2 + marks3;
        double averageMarks = totalMarks / 3.0;
        System.out.println("The average marks are: " + averageMarks);

    }
}
